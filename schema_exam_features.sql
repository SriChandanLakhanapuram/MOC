-- ExamFlow exam catalog, faculty assignment, enrollments and refunds.
-- Additive migration for the existing MOC_PROJECT schema. Run once as
-- MOC_PROJECT after schema_patch.sql has been applied.

CREATE TABLE EXAMS (
    EXAM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EXAM_CODE VARCHAR2(20) NOT NULL UNIQUE,
    EXAM_NAME VARCHAR2(120) NOT NULL,
    COURSE_CODE VARCHAR2(10) NOT NULL REFERENCES COURSES(COURSE_CODE),
    EXAM_DATE DATE NOT NULL,
    FEE NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (FEE >= 0),
    STATUS VARCHAR2(12) DEFAULT 'Open' NOT NULL CHECK (STATUS IN ('Draft','Open','Closed')),
    CREATED_BY NUMBER NOT NULL REFERENCES USERS(USER_ID),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE EXAM_FACULTY (
    EXAM_ID NUMBER NOT NULL REFERENCES EXAMS(EXAM_ID) ON DELETE CASCADE,
    FACULTY_ID VARCHAR2(10) NOT NULL REFERENCES FACULTY(FACULTY_ID),
    ASSIGNED_BY NUMBER NOT NULL REFERENCES USERS(USER_ID),
    ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EXAM_FACULTY PRIMARY KEY (EXAM_ID, FACULTY_ID)
);

CREATE TABLE EXAM_ENROLLMENTS (
    ENROLLMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID VARCHAR2(10) NOT NULL REFERENCES STUDENTS(STUDENT_ID),
    EXAM_ID NUMBER NOT NULL REFERENCES EXAMS(EXAM_ID),
    EXAM_STATUS VARCHAR2(20) DEFAULT 'Registered' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_EXAM_ENROLLMENT UNIQUE (STUDENT_ID, EXAM_ID),
    CONSTRAINT CK_ENROLLMENT_STATUS CHECK (EXAM_STATUS IN (
        'Registered','FeePaid','HallTicketIssued','ExamTaken','Evaluated',
        'UnderReview','ResultPublished','Cancelled','Absent'))
);

CREATE TABLE REFUND_REQUESTS (
    REFUND_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENROLLMENT_ID NUMBER NOT NULL REFERENCES EXAM_ENROLLMENTS(ENROLLMENT_ID),
    REQUESTED_BY NUMBER NOT NULL REFERENCES USERS(USER_ID),
    REASON VARCHAR2(500) NOT NULL,
    STATUS VARCHAR2(12) DEFAULT 'Pending' NOT NULL
        CHECK (STATUS IN ('Pending','Approved','Rejected')),
    REVIEWED_BY NUMBER REFERENCES USERS(USER_ID),
    REQUESTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_AT TIMESTAMP,
    REVIEW_NOTE VARCHAR2(500)
);

CREATE TABLE EVALUATION_HISTORY (
    HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MARK_ID NUMBER NOT NULL REFERENCES MARKS(MARK_ID),
    CHANGED_BY NUMBER NOT NULL REFERENCES USERS(USER_ID),
    OLD_MARKS NUMBER(5,2), NEW_MARKS NUMBER(5,2) NOT NULL,
    OLD_GRADE VARCHAR2(5), NEW_GRADE VARCHAR2(5),
    REASON VARCHAR2(500) NOT NULL,
    CHANGED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

ALTER TABLE FEE_PAYMENTS ADD (ENROLLMENT_ID NUMBER REFERENCES EXAM_ENROLLMENTS(ENROLLMENT_ID));
ALTER TABLE HALL_TICKETS ADD (ENROLLMENT_ID NUMBER REFERENCES EXAM_ENROLLMENTS(ENROLLMENT_ID));
ALTER TABLE MARKS ADD (ENROLLMENT_ID NUMBER REFERENCES EXAM_ENROLLMENTS(ENROLLMENT_ID));
ALTER TABLE AUDIT_LOG ADD (ENROLLMENT_ID NUMBER REFERENCES EXAM_ENROLLMENTS(ENROLLMENT_ID));

ALTER TABLE FEE_PAYMENTS DROP CONSTRAINT CK_PAYMENT_STATUS;
ALTER TABLE FEE_PAYMENTS ADD CONSTRAINT CK_PAYMENT_STATUS
    CHECK (STATUS IN ('Success','Failed','Refunded'));

-- Create one visible legacy exam per existing course so existing student
-- records and payments appear in the new exam-centered screens.
MERGE INTO EXAMS e
USING (
    SELECT 'LEGACY-' || c.COURSE_CODE AS EXAM_CODE,
           c.COURSE_NAME || ' — Existing exam' AS EXAM_NAME,
           c.COURSE_CODE, SYSDATE + 30 AS EXAM_DATE,
           1000 AS FEE,
           (SELECT MIN(USER_ID) FROM USERS WHERE ROLE = 'ExamCell') AS CREATED_BY
    FROM COURSES c
) src
ON (e.EXAM_CODE = src.EXAM_CODE)
WHEN NOT MATCHED THEN INSERT
    (EXAM_CODE, EXAM_NAME, COURSE_CODE, EXAM_DATE, FEE, STATUS, CREATED_BY)
VALUES (src.EXAM_CODE, src.EXAM_NAME, src.COURSE_CODE, src.EXAM_DATE,
        src.FEE, 'Open', src.CREATED_BY);

INSERT INTO EXAM_ENROLLMENTS (STUDENT_ID, EXAM_ID, EXAM_STATUS)
SELECT s.STUDENT_ID, e.EXAM_ID, s.EXAM_STATUS
FROM STUDENTS s
JOIN EXAMS e ON e.EXAM_CODE = 'LEGACY-' || s.COURSE_CODE
WHERE NOT EXISTS (
    SELECT 1 FROM EXAM_ENROLLMENTS x
    WHERE x.STUDENT_ID = s.STUDENT_ID AND x.EXAM_ID = e.EXAM_ID
);

UPDATE FEE_PAYMENTS p SET ENROLLMENT_ID = (
    SELECT x.ENROLLMENT_ID FROM EXAM_ENROLLMENTS x
    JOIN EXAMS e ON e.EXAM_ID = x.EXAM_ID
    WHERE x.STUDENT_ID = p.STUDENT_ID AND e.EXAM_CODE = 'LEGACY-' ||
          (SELECT s.COURSE_CODE FROM STUDENTS s WHERE s.STUDENT_ID = p.STUDENT_ID)
)
WHERE ENROLLMENT_ID IS NULL;

UPDATE HALL_TICKETS h SET ENROLLMENT_ID = (
    SELECT x.ENROLLMENT_ID FROM EXAM_ENROLLMENTS x
    JOIN STUDENTS s ON s.STUDENT_ID = x.STUDENT_ID
    WHERE x.STUDENT_ID = h.STUDENT_ID AND x.EXAM_ID = (
        SELECT e.EXAM_ID FROM EXAMS e WHERE e.EXAM_CODE = 'LEGACY-' || s.COURSE_CODE
    )
)
WHERE ENROLLMENT_ID IS NULL;

UPDATE MARKS m SET ENROLLMENT_ID = (
    SELECT x.ENROLLMENT_ID FROM EXAM_ENROLLMENTS x
    JOIN STUDENTS s ON s.STUDENT_ID = x.STUDENT_ID
    JOIN EXAMS e ON e.EXAM_ID = x.EXAM_ID AND e.COURSE_CODE = m.COURSE_CODE
    WHERE x.STUDENT_ID = m.STUDENT_ID AND e.EXAM_CODE = 'LEGACY-' || s.COURSE_CODE
)
WHERE ENROLLMENT_ID IS NULL;

INSERT INTO EXAM_FACULTY (EXAM_ID, FACULTY_ID, ASSIGNED_BY)
SELECT e.EXAM_ID, f.FACULTY_ID,
       (SELECT MIN(USER_ID) FROM USERS WHERE ROLE = 'ExamCell')
FROM EXAMS e
JOIN COURSES c ON c.COURSE_CODE = e.COURSE_CODE
JOIN FACULTY f ON f.DEPARTMENT = c.DEPARTMENT
WHERE NOT EXISTS (
    SELECT 1 FROM EXAM_FACULTY x WHERE x.EXAM_ID = e.EXAM_ID AND x.FACULTY_ID = f.FACULTY_ID
);

DELETE FROM PERMISSIONS WHERE ROLE = 'Admin' AND EVENT = 'request_refund';
MERGE INTO PERMISSIONS p
USING (SELECT 'ExamCell' ROLE, 'request_refund' EVENT FROM dual) x
ON (p.ROLE = x.ROLE AND p.EVENT = x.EVENT)
WHEN NOT MATCHED THEN INSERT (ROLE, EVENT) VALUES (x.ROLE, x.EVENT);

CREATE INDEX IX_ENROLLMENT_EXAM_STATE ON EXAM_ENROLLMENTS(EXAM_ID, EXAM_STATUS);
CREATE INDEX IX_REFUND_STATUS_TIME ON REFUND_REQUESTS(STATUS, REQUESTED_AT);
CREATE INDEX IX_ASSIGNMENT_FACULTY ON EXAM_FACULTY(FACULTY_ID, EXAM_ID);

COMMIT;
