-- HOD course catalog and teaching assignment management.
-- Run once after schema_exam_features.sql as the MOC_PROJECT schema user.

CREATE TABLE HOD_DEPARTMENTS (
    USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    DEPARTMENT VARCHAR2(50) NOT NULL,
    ASSIGNED_BY NUMBER REFERENCES USERS(USER_ID),
    ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HOD_DEPARTMENTS PRIMARY KEY (USER_ID, DEPARTMENT)
);

CREATE TABLE COURSE_FACULTY (
    ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COURSE_CODE VARCHAR2(10) NOT NULL REFERENCES COURSES(COURSE_CODE),
    FACULTY_ID VARCHAR2(10) NOT NULL REFERENCES FACULTY(FACULTY_ID),
    ACADEMIC_YEAR VARCHAR2(9) NOT NULL,
    TERM VARCHAR2(30) NOT NULL,
    ASSIGNMENT_ROLE VARCHAR2(20) DEFAULT 'Instructor' NOT NULL
        CHECK (ASSIGNMENT_ROLE IN ('Lead','Co-instructor','Lab instructor')),
    ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL CHECK (ACTIVE IN ('Y','N')),
    ASSIGNED_BY NUMBER NOT NULL REFERENCES USERS(USER_ID),
    ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ENDED_BY NUMBER REFERENCES USERS(USER_ID),
    ENDED_AT TIMESTAMP
);

-- Give each HOD ownership of their existing/home department where available.
INSERT INTO HOD_DEPARTMENTS (USER_ID, DEPARTMENT, ASSIGNED_BY)
SELECT u.USER_ID, c.DEPARTMENT, (SELECT MIN(USER_ID) FROM USERS WHERE ROLE='Admin')
FROM USERS u
JOIN FACULTY f ON f.USER_ID=u.USER_ID
JOIN COURSES c ON c.DEPARTMENT=f.DEPARTMENT
WHERE u.ROLE='HOD'
  AND NOT EXISTS (SELECT 1 FROM HOD_DEPARTMENTS h WHERE h.USER_ID=u.USER_ID AND h.DEPARTMENT=c.DEPARTMENT);

INSERT INTO HOD_DEPARTMENTS (USER_ID, DEPARTMENT, ASSIGNED_BY)
SELECT u.USER_ID,(SELECT MIN(DEPARTMENT) FROM COURSES),
       (SELECT MIN(USER_ID) FROM USERS WHERE ROLE='Admin')
FROM USERS u
WHERE u.ROLE='HOD'
  AND EXISTS (SELECT 1 FROM COURSES)
  AND NOT EXISTS (SELECT 1 FROM HOD_DEPARTMENTS h WHERE h.USER_ID=u.USER_ID);

-- Seed current-term teaching assignments from existing department matches.
INSERT INTO COURSE_FACULTY
    (COURSE_CODE,FACULTY_ID,ACADEMIC_YEAR,TERM,ASSIGNMENT_ROLE,ASSIGNED_BY)
SELECT c.COURSE_CODE,f.FACULTY_ID,
       TO_CHAR(SYSDATE,'YYYY')||'-'||TO_CHAR(ADD_MONTHS(SYSDATE,12),'YY'),
       'Term 1','Lead',(SELECT MIN(USER_ID) FROM USERS WHERE ROLE='Admin')
FROM COURSES c JOIN FACULTY f ON f.DEPARTMENT=c.DEPARTMENT
WHERE NOT EXISTS (
    SELECT 1 FROM COURSE_FACULTY a
    WHERE a.COURSE_CODE=c.COURSE_CODE AND a.FACULTY_ID=f.FACULTY_ID
      AND a.ACADEMIC_YEAR=TO_CHAR(SYSDATE,'YYYY')||'-'||TO_CHAR(ADD_MONTHS(SYSDATE,12),'YY')
      AND a.TERM='Term 1'
);

CREATE INDEX IX_HOD_DEPT ON HOD_DEPARTMENTS(DEPARTMENT,USER_ID);
CREATE UNIQUE INDEX UQ_COURSE_FACULTY_ACTIVE ON COURSE_FACULTY
    (CASE WHEN ACTIVE='Y' THEN COURSE_CODE END,
     CASE WHEN ACTIVE='Y' THEN FACULTY_ID END,
     CASE WHEN ACTIVE='Y' THEN ACADEMIC_YEAR END,
     CASE WHEN ACTIVE='Y' THEN TERM END);
CREATE UNIQUE INDEX UQ_COURSE_LEAD_ACTIVE ON COURSE_FACULTY
    (CASE WHEN ACTIVE='Y' AND ASSIGNMENT_ROLE='Lead' THEN COURSE_CODE END,
     CASE WHEN ACTIVE='Y' AND ASSIGNMENT_ROLE='Lead' THEN ACADEMIC_YEAR END,
     CASE WHEN ACTIVE='Y' AND ASSIGNMENT_ROLE='Lead' THEN TERM END);
CREATE INDEX IX_COURSE_FACULTY_COURSE ON COURSE_FACULTY(COURSE_CODE,ACTIVE,FACULTY_ID);
COMMIT;
