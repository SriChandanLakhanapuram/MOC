--------------------------------------------------------
-- 1. USERS
--------------------------------------------------------

CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 100 INCREMENT BY 1)
        PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL,
    CONSTRAINT CK_USERS_ROLE
        CHECK (ROLE IN ('Admin','Student','Faculty','HOD','ExamCell')),
    CONSTRAINT UQ_USERS_EMAIL
        UNIQUE (EMAIL)
);

--------------------------------------------------------
-- 2. COURSES
--------------------------------------------------------

CREATE TABLE COURSES (
    COURSE_CODE VARCHAR2(10) PRIMARY KEY,
    COURSE_NAME VARCHAR2(100) NOT NULL,
    DEPARTMENT VARCHAR2(50) NOT NULL,
    CREDITS NUMBER NOT NULL
);

--------------------------------------------------------
-- 3. PERMISSIONS
--------------------------------------------------------

CREATE TABLE PERMISSIONS (
    ROLE VARCHAR2(20) NOT NULL,
    EVENT VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_PERMISSIONS
        PRIMARY KEY (ROLE, EVENT),
    CONSTRAINT CK_PERMISSIONS_ROLE
        CHECK (ROLE IN ('Admin','Student','Faculty','HOD','ExamCell'))
);

--------------------------------------------------------
-- 4. STUDENTS
--------------------------------------------------------

CREATE TABLE STUDENTS (
    STUDENT_ID VARCHAR2(10) PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    COURSE_CODE VARCHAR2(10) NOT NULL,
    EXAM_STATUS VARCHAR2(20) DEFAULT 'Registered' NOT NULL,

    CONSTRAINT CK_STUDENT_STATUS
        CHECK (
            EXAM_STATUS IN (
                'Registered',
                'FeePaid',
                'HallTicketIssued',
                'ExamTaken',
                'Evaluated',
                'UnderReview',
                'ResultPublished',
                'Cancelled',
                'Absent'
            )
        )
);

--------------------------------------------------------
-- 5. FACULTY
--------------------------------------------------------

CREATE TABLE FACULTY (
    FACULTY_ID VARCHAR2(10) PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    DEPARTMENT VARCHAR2(50) NOT NULL
);

--------------------------------------------------------
-- 6. FEE PAYMENTS
--------------------------------------------------------

CREATE TABLE FEE_PAYMENTS (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    STUDENT_ID VARCHAR2(10) NOT NULL,
    AMOUNT NUMBER(10,2) NOT NULL,
    PAYMENT_DATE DATE NOT NULL,
    STATUS VARCHAR2(10) NOT NULL,

    CONSTRAINT CK_PAYMENT_STATUS
        CHECK (STATUS IN ('Success','Failed'))
);

--------------------------------------------------------
-- 7. HALL TICKETS
--------------------------------------------------------

CREATE TABLE HALL_TICKETS (
    TICKET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    STUDENT_ID VARCHAR2(10) NOT NULL,
    EXAM_DATE DATE NOT NULL,
    ISSUED_BY NUMBER NOT NULL
);

--------------------------------------------------------
-- 8. MARKS
--------------------------------------------------------

CREATE TABLE MARKS (
    MARK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    STUDENT_ID VARCHAR2(10) NOT NULL,
    COURSE_CODE VARCHAR2(10) NOT NULL,
    MARKS_OBTAINED NUMBER(5,2),
    ENTERED_BY VARCHAR2(10) NOT NULL,
    VERIFIED_BY NUMBER
);

--------------------------------------------------------
-- 9. AUDIT LOG
--------------------------------------------------------

CREATE TABLE AUDIT_LOG (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 3 INCREMENT BY 1)
        PRIMARY KEY,
    USER_ID NUMBER,
    STUDENT_ID VARCHAR2(10),
    EVENT VARCHAR2(30) NOT NULL,
    OLD_STATE VARCHAR2(30),
    NEW_STATE VARCHAR2(30),
    LOG_TIME TIMESTAMP(6) DEFAULT SYSTIMESTAMP
);

